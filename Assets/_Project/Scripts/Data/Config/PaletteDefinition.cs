using System;
using UnityEngine;

namespace BeachTycoon.Data
{
    [Serializable]
    public struct PaletteEntry
    {
        public string key;
        public Color color;
        [UnityEngine.Range(0f, 1f)] public float smoothness;
        [UnityEngine.Range(0f, 1f)] public float metallic;
        [Tooltip("Optional tileable detail texture, tinted by color.")]
        public Texture2D texture;
        public Vector2 tiling;
        [Tooltip("Generated by Beach Tycoon > Setup. Re-run it after changing the entry.")]
        public Material material;
    }

    /// <summary>The single shared flat-color palette. Every placeholder material comes from here.</summary>
    [CreateAssetMenu(menuName = "Beach Tycoon/Palette", fileName = "Palette")]
    public sealed class PaletteDefinition : ScriptableObject
    {
        /// <summary>Setup upgrades older palettes (new surface settings) while keeping tuned colours. 0 = never upgraded.</summary>
        public int dataVersion;

        public PaletteEntry[] entries;

        /// <summary>Linear lookup; call at build/setup time only, not per frame.</summary>
        public Material GetMaterial(string key)
        {
            int index = IndexOf(key);
            return index >= 0 ? entries[index].material : null;
        }

        public Color GetColor(string key)
        {
            int index = IndexOf(key);
            return index >= 0 ? entries[index].color : Color.magenta;
        }

        private int IndexOf(string key)
        {
            if (entries != null)
            {
                for (int i = 0; i < entries.Length; i++)
                {
                    if (entries[i].key == key)
                    {
                        return i;
                    }
                }
            }

            Debug.LogWarning($"Palette has no entry '{key}'.", this);
            return -1;
        }
    }
}
